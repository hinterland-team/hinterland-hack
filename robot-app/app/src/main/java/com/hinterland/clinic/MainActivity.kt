package com.hinterland.clinic

import android.os.Bundle
import android.view.WindowManager
import androidx.activity.compose.setContent
import androidx.appcompat.app.AppCompatActivity
import androidx.compose.runtime.collectAsState
import androidx.compose.runtime.getValue
import androidx.core.view.WindowCompat
import androidx.core.view.WindowInsetsCompat
import androidx.core.view.WindowInsetsControllerCompat
import androidx.lifecycle.Lifecycle
import androidx.lifecycle.lifecycleScope
import androidx.lifecycle.repeatOnLifecycle
import com.ainirobot.agent.AgentCore
import com.ainirobot.agent.OnAgentStatusChangedListener
import com.ainirobot.agent.OnTranscribeListener
import com.ainirobot.agent.PageAgent
import com.ainirobot.agent.base.Transcription
import com.hinterland.clinic.ui.ClinicScreen
import com.hinterland.clinic.ui.NovaTheme
import com.hinterland.clinic.ui.ScreenActions
import kotlinx.coroutines.launch

class MainActivity : AppCompatActivity() {

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        window.addFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON)
        WindowCompat.setDecorFitsSystemWindows(window, false)
        hideSystemBars()

        // page actions are live while this screen is visible. listeners return false
        // so the agent keeps handling speech as usual (the voice bar itself is off, see onStart).
        PageAgent(this)
            .registerActions(ClinicActions.all())
            .setOnTranscribeListener(object : OnTranscribeListener {
                override fun onASRResult(transcription: Transcription): Boolean {
                    Clinic.onUserSpeech(transcription.text, transcription.final)
                    return false
                }

                override fun onTTSResult(transcription: Transcription): Boolean {
                    Clinic.onRobotSpeech(transcription.text, transcription.final)
                    return false
                }
            })
            .setOnAgentStatusChangedListener(object : OnAgentStatusChangedListener {
                override fun onStatusChanged(status: String, message: String?): Boolean {
                    Clinic.onAgentStatus(status, message)
                    return false
                }
            })

        Robot.onHealth = Clinic::onRobotHealth

        // the screen's buttons: "That's me", pace, "I'm here", feedback and the self check-in steps
        val actions = ScreenActions(
            thatsMe = Clinic::tapThatsMe,
            pace = Clinic::tapPace,
            imHere = Clinic::tapImHere,
            goOn = Clinic::tapGoOn,
            feedback = Clinic::tapFeedback,
            checkIn = Clinic::tapCheckIn,
            room = Clinic::tapRoom,
            checkInPace = Clinic::tapCheckInPace,
            checkInBack = Clinic::tapCheckInBack,
            checkInClose = Clinic::tapCheckInClose,
            checkInConfirm = Clinic::tapCheckInConfirm,
            allGood = Clinic::tapAllGood,
            talkSlower = Clinic::tapTalkSlower,
            talkWait = Clinic::tapTalkWait,
            openStaff = Clinic::openStaff,
            closeStaff = Clinic::closeStaff,
            staffTouched = Clinic::staffTouched,
            recheckServers = Clinic::staffRecheckServers,
        )

        setContent {
            NovaTheme {
                val state by Clinic.ui.collectAsState()
                ClinicScreen(state, actions)
            }
        }

        // otto's brain runs while this screen is in front: it greets, takes the team's guide commands,
        // charges and goes home on its own, and sends the heartbeat and the live feed
        lifecycleScope.launch {
            repeatOnLifecycle(Lifecycle.State.RESUMED) {
                Robot.connect(this@MainActivity)
                Clinic.refreshScreenInfo()
                // frame times, dropped frames and cpu for the staff menu and the log (6.7), main thread
                launch { PerfMonitor.run(this@MainActivity) }
                OttoBrain.run()
            }
        }
    }

    // our screen shows what otto says, so the system voice bar (subtitle, "tap to interrupt",
    // "content generated by AI") is off while we are in front (AgentOS SDK 4.5 Voice Bar Control).
    // voice and barge-in keep working. other apps get the bar back when we leave
    override fun onStart() {
        super.onStart()
        voiceBar(false)
    }

    override fun onResume() {
        super.onResume()
        voiceBar(false)
        hideSystemBars()
    }

    // dialogs and edge swipes bring the bars back, hide them again when we get focus
    override fun onWindowFocusChanged(hasFocus: Boolean) {
        super.onWindowFocusChanged(hasFocus)
        if (hasFocus) hideSystemBars()
    }

    override fun onStop() {
        voiceBar(true)
        super.onStop()
    }

    // full screen: the system navigation bar (the side panel with the arrow) and the status bar
    // stay hidden. a swipe from the edge shows them for a moment
    private fun hideSystemBars() {
        WindowInsetsControllerCompat(window, window.decorView).apply {
            hide(WindowInsetsCompat.Type.systemBars())
            systemBarsBehavior = WindowInsetsControllerCompat.BEHAVIOR_SHOW_TRANSIENT_BARS_BY_SWIPE
        }
    }

    private fun voiceBar(on: Boolean) {
        runCatching { AgentCore.isEnableVoiceBar = on }
            .onFailure { RobotLog.w(LogSource.VOICE, "Voice bar switch failed: ${it.message}") }
    }
}
